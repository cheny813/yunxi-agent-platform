package io.yunxi.platform.trace;

/**
 * 推理轨迹节点的种类。
 *
 * <p>轨迹是 Agent 一次运行的可观测表示：一个用户回合对应一棵树，树的每个节点是一个 span。
 * 本枚举定义节点种类，与框架细粒度事件的对应关系在归集层建立。</p>
 *
 * <p>种类划分遵循「一个种类对应一类可独立展示与回放的信息」：用户可见的回合边界、模型调用、
 * 文本与思考输出、工具调用及其结果、人机交互、子代理、意图识别、计划与任务、控制信号等。
 * 新增种类需要同时确定其负载结构与归集规则，不应由单个事件临时派生。</p>
 *
 * @author yunxi-agent-platform
 */
public enum SpanKind {

    /** 一个用户回合，树根 */
    TURN,

    /** 一次模型调用 */
    MODEL_CALL,

    /** 文本输出块 */
    TEXT,

    /** 思考过程块 */
    REASONING,

    /** 结构化数据块 */
    DATA,

    /** 工具调用（含其结果的终态） */
    TOOL_CALL,

    /** 人机交互：确认请求与外部执行请求 */
    HITL,

    /** 子代理 */
    SUBAGENT,

    /** 意图识别节点 */
    INTENT,

    /** 计划（全量快照） */
    PLAN,

    /** 单个任务的变更 */
    TASK,

    /** 控制信号：中断、超出迭代上限、全部工具被拒等 */
    CONTROL,

    /** 其余自定义事件 */
    CUSTOM
}
